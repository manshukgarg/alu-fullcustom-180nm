#!/bin/bash
# Step 5: the project cell library pl018 and the automated ALU built with it (design D4).
# Same flow as Step 2 (design D3, OSU018 cells), with the project's own cells:
#   1. Magic DRC and extraction of every library cell; Netgen LVS against the drawn netlists
#   2. Ngspice characterization of the extracted cells -> tech/pl018/pl018_cells.lib
#   3. Yosys synthesis of both RTL models onto the library, exhaustive gate-level simulation, OpenSTA
#   4. Qflow synthesis, placement, routing, migration and LVS with the library (tech/pl018)
#   5. Magic DRC of both routed layouts with the real cell layouts, transistor-level extraction
#   6. Ngspice ALU testbench (sim/alutb.py) on every layout and its cell-level netlist
# The cell layouts in mag/pl_*.mag and the views in tech/pl018 are generated by
# step5_library/gen_library.py (not run here).
# Usage (from the repository root):  bash step5_library/run.sh      (about 15-25 minutes)
cd "$(dirname "$0")" || exit 1
ROOT=$(cd .. && pwd)
TECH=$ROOT/tech/pl018
OSU=/apps/vlsi/share/qflow/tech/osu018
LIB=$TECH/pl018_cells.lib
DESIGNS="beh slice"
rtl() { if [ "$1" = beh ]; then echo ../rtl/alu4.v; else echo ../rtl/alu4_slice.v; fi; }
rm -rf out qflow_beh qflow_slice
mkdir -p out/cells out/sim

# Magic start-up file of the technology, with the absolute paths of this checkout
cat > "$TECH/pl018.magicrc" <<EOF
# .magicrc for the pl018 library under qflow (written by step5_library/run.sh)
path sys +$OSU
tech load SCN6M_SUBM.10 -noprompt
set GND gnd
set VDD vdd
drc euclidean on
drc off
addpath $ROOT/mag
EOF
python3 -c "import json; print(' '.join(c['name'] for c in json.load(open('cells.json'))['cells']))" \
    > out/cells.txt
N=$(wc -w < out/cells.txt)

echo "[1/6] DRC, extraction and LVS of the $N library cells (magic, netgen)"
(cd out/cells && magic -dnull -noconsole -rcfile ../../../tech/magicrc ../../cells.tcl > magic.log 2>&1)
for c in $(cat out/cells.txt); do
    [ "$c" = pl_fill ] && continue
    netgen -batch lvs "out/cells/${c}_lvs.spice $c" "$TECH/pl018_cells.sp $c" \
        "$TECH/pl018_setup.tcl" "out/cells/${c}_lvs.out" > "out/cells/${c}_netgen.log" 2>&1
done

echo "[2/6] characterization of the extracted cells (ngspice), a few minutes"
python3 characterize.py > out/characterization.txt 2>&1
tail -12 out/characterization.txt

echo "[3/6] synthesis onto the library (yosys), gate-level simulation, static timing (OpenSTA)"
for d in $DESIGNS; do
    cat > out/synth_$d.ys <<EOF
read_verilog $(rtl $d)
synth -top alu4 -flatten
abc -liberty $LIB
opt_clean -purge
stat -liberty $LIB
write_verilog -noattr -noexpr out/${d}_syn.v
EOF
    yosys -s out/synth_$d.ys > out/yosys_$d.log 2>&1
    iverilog -g2012 -o out/sim_$d ../tb/tb_alu4.v "$(rtl $d)" > out/iverilog_$d.log 2>&1
    vvp -n out/sim_$d > out/sim_$d.log 2>&1
    iverilog -g2012 -DGATE -o out/sim_gate_$d ../tb/tb_alu4.v out/${d}_syn.v "$TECH/pl018_cells.v" \
        > out/iverilog_gate_$d.log 2>&1
    vvp -n out/sim_gate_$d > out/sim_gate_$d.log 2>&1
    cat > out/sta_$d.tcl <<EOF
read_liberty $LIB
read_verilog out/${d}_syn.v
link_design alu4
create_clock -name vclk -period 10
set_input_delay 0 -clock vclk [all_inputs]
set_output_delay 0 -clock vclk [all_outputs]
set_input_transition 0.05 [all_inputs]
set_load 0.01 [all_outputs]
report_checks -path_delay max -digits 3
exit
EOF
    sta -no_splash -exit out/sta_$d.tcl > out/sta_$d.log 2>&1
done

echo "[4/6] automated place and route with the library (qflow), 1-3 minutes each"
for d in $DESIGNS; do
    q=qflow_$d
    mkdir -p $q/source $q/synthesis $q/layout $q/log
    cp "$(rtl $d)" $q/source/alu4.v
    # no post-route timing step (backanno): it does not change the layout, and the timing
    # comes from OpenSTA above and from the transistor-level simulation below
    (cd $q && QFLOW_TECH_DIR="$TECH" qflow -T pl018 synthesize place route migrate lvs alu4 \
        > ../out/qflow_$d.log 2>&1)
done

echo "[5/6] DRC with real cell layouts and transistor-level extraction (magic)"
for d in $DESIGNS; do
    if [ -f qflow_$d/layout/alu4.mag ]; then
        printf 'set PL_CELLS {%s}\nset PL_MAG %s\n' "$(cat out/cells.txt)" "$ROOT/mag" \
            > qflow_$d/layout/pl_cells.tcl
        (cd qflow_$d/layout && magic -dnull -noconsole ../../layout_check.tcl > ../../out/magic_$d.log 2>&1)
    else
        echo "ERROR: qflow_$d/layout/alu4.mag not created (see out/qflow_$d.log)" > out/magic_$d.log
    fi
done

echo "[6/6] transistor-level simulation (ngspice): 4 netlists, a few minutes each"
for d in $DESIGNS; do
    python3 ../sim/alutb.py qflow_$d/layout/alu4_pex.spice --top alu4 --width 4 \
        --label ${d}_post --out out/sim > out/sim/${d}_post.out 2>&1 &
done
wait
for d in $DESIGNS; do
    python3 ../sim/alutb.py qflow_$d/synthesis/alu4.spc --lib "$TECH/pl018_cells.sp" \
        --top alu4 --width 4 --label ${d}_pre --out out/sim > out/sim/${d}_pre.out 2>&1 &
done
wait

python3 summary.py | tee out/summary.txt
