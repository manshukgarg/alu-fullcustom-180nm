#!/usr/bin/env python3
"""Generate the layouts of both cell libraries (Step 4).

For every cell of library.json the transistor netlist of step3_cells/cellnet.py
is placed and routed by layout/cellgen.py, checked with the project's rule
checker (layout/drc.py) and connectivity extractor (layout/extract.py), and
written as:
    mag/<name>.mag               Magic layout (SCN6M_SUBM.10, lambda = 0.1 um)
    step4_layout/ref/<name>.spice  LVS reference netlist (devices as laid out)
    step4_layout/cells.json      cell list, sizes, pins and pin pads
    docs/figures/cells/<name>.png  layout preview (with --preview)

This step needs numpy (and matplotlib for previews); it is run once when the
library changes, not in the lab. The lab flow (run.sh) only reads its output.

Usage:  python3 step4_layout/gen_cells.py [--only name,name] [--preview] [--jobs N]
"""
import argparse
import json
import multiprocessing as mp
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "layout"))

import library  # noqa: E402
from template import H  # noqa: E402


def build(job):
    lib, family, spec, preview = job
    t0 = time.time()
    cell, b = library.make_cell(spec["cell"], spec["k"], spec["r"], name=spec["name"])
    try:
        L = b.build()
    except Exception as err:          # report and continue with the other cells
        return {"name": spec["name"], "lib": lib, "family": family, "failed": str(err),
                "seconds": round(time.time() - t0, 1)}
    errors, problems, ndev = b.verify(L)
    out = {
        "name": spec["name"], "lib": lib, "family": family, "cell": spec["cell"],
        "k": spec["k"], "r": spec["r"], "transistors": cell.count, "devices_drawn": ndev,
        "width_lambda": b.width, "height_lambda": H,
        "width_um": b.width / 10.0, "height_um": H / 10.0,
        "area_um2": round(b.width * H / 100.0, 2),
        "inputs": cell.inputs, "outputs": cell.outputs,
        "pins": {p: list(b.pads[p]) for p in cell.inputs + cell.outputs},
        "drc_errors": errors, "lvs_problems": problems,
        "seconds": round(time.time() - t0, 1),
    }
    L.write(os.path.join(ROOT, "mag", spec["name"] + ".mag"))
    with open(os.path.join(HERE, "ref", spec["name"] + ".spice"), "w") as f:
        f.write("* LVS reference for %s: %s at k = %g, r = %g (devices as laid out)\n"
                % (spec["name"], spec["cell"], spec["k"], spec["r"]))
        f.write(b.reference_netlist())
    if preview:
        import preview as pv
        d = os.path.join(ROOT, "docs", "figures", "cells")
        os.makedirs(d, exist_ok=True)
        pv.render(L, os.path.join(d, spec["name"] + ".png"), scale=0.12)
    return out


def index(lib):
    """cells.json from the Magic files already in mag/ (bounding box and pin labels)."""
    import cellnet
    cells = []
    for libname in ("optimized", "conventional"):
        for family, spec in lib[libname].items():
            path = os.path.join(ROOT, "mag", spec["name"] + ".mag")
            if not os.path.exists(path):
                print("missing", spec["name"])
                continue
            cell = getattr(cellnet, spec["cell"])(spec["k"], spec["r"])
            bbox, pins = None, {}
            for line in open(path):
                f = line.split()
                if line.startswith("string FIXED_BBOX"):
                    bbox = [int(v) for v in f[2:6]]
                elif line.startswith("rlabel") and f[-1] in cell.inputs + cell.outputs:
                    layer = {"metal1": "m1", "metal2": "m2"}[f[1]]
                    pins[f[-1]] = [layer] + [int(v) for v in f[3:7]]
            w = bbox[2] - bbox[0]
            cells.append({"name": spec["name"], "lib": libname, "family": family,
                          "cell": spec["cell"], "k": spec["k"], "r": spec["r"],
                          "transistors": cell.count, "width_lambda": w, "height_lambda": H,
                          "width_um": w / 10.0, "height_um": H / 10.0,
                          "area_um2": round(w * H / 100.0, 2), "inputs": cell.inputs,
                          "outputs": cell.outputs, "pins": pins})
    with open(os.path.join(HERE, "cells.json"), "w") as f:
        json.dump({"note": "generated by step4_layout/gen_cells.py; lambda = 0.1 um",
                   "cells": cells}, f, indent=1)
    print("cells.json: %d cells" % len(cells))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--preview", action="store_true")
    ap.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 2)))
    ap.add_argument("--index", action="store_true",
                    help="only rebuild cells.json from the existing mag/ files")
    args = ap.parse_args()
    lib = json.load(open(os.path.join(HERE, "library.json")))
    if args.index:
        index(lib)
        return
    os.makedirs(os.path.join(HERE, "ref"), exist_ok=True)
    jobs = []
    for libname in ("optimized", "conventional"):
        for family, spec in lib[libname].items():
            if args.only and spec["name"] not in args.only.split(","):
                continue
            jobs.append((libname, family, spec, args.preview))
    # the slowest cells first
    jobs.sort(key=lambda j: -len(library.PLANS[j[2]["cell"]]))
    path = os.path.join(HERE, "cells.json")
    old = {c["name"]: c for c in json.load(open(path))["cells"]} if os.path.exists(path) else {}
    results = {}
    with mp.Pool(min(args.jobs, len(jobs))) as pool:
        for r in pool.imap_unordered(build, jobs):
            if "failed" in r:
                print("%-11s FAILED after %.0fs: %s" % (r["name"], r["seconds"], r["failed"]), flush=True)
                continue
            results[r["name"]] = r
            ok = "clean" if not r["drc_errors"] and not r["lvs_problems"] else "PROBLEM"
            print("%-11s %5.1f x %.1f um  %2d transistors  %5.1fs  %s %s"
                  % (r["name"], r["width_um"], r["height_um"], r["transistors"], r["seconds"], ok,
                     (r["drc_errors"] + r["lvs_problems"])[:3]), flush=True)
    old.update(results)
    order = []
    for libname in ("optimized", "conventional"):
        for family, spec in lib[libname].items():
            if spec["name"] in old:
                order.append(old[spec["name"]])
    with open(path, "w") as f:
        json.dump({"note": "generated by step4_layout/gen_cells.py; lambda = 0.1 um",
                   "cells": order}, f, indent=1)
    bad = [r["name"] for r in results.values() if r["drc_errors"] or r["lvs_problems"]]
    bad += [j[2]["name"] for j in jobs if j[2]["name"] not in results]
    if bad:
        print("cells with problems:", ", ".join(bad))
        sys.exit(1)


if __name__ == "__main__":
    main()
